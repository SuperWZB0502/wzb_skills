#!/usr/bin/env python3
"""Capture the two real report features for the skill's introduction.

Optional documentation helper; normal report generation does not need Playwright.
"""
import argparse
import hashlib
import json
from pathlib import Path


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--html',type=Path,required=True,help='HTML generated by run_analysis.py')
    p.add_argument('--output-dir',type=Path,default=Path(__file__).resolve().parents[1]/'assets/previews')
    args=p.parse_args()
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        p.error('截图工具需要Playwright和Chromium；正常生成HTML不需要此依赖。')
    source=args.html.expanduser().resolve()
    if not source.is_file():p.error('HTML不存在：'+str(source))
    out=args.output_dir.expanduser().resolve();out.mkdir(parents=True,exist_ok=True)
    errors=[];requests=[];shots=[]
    with sync_playwright() as playwright:
        browser=playwright.chromium.launch(headless=True,args=['--no-sandbox'])
        page=browser.new_page(viewport={'width':1600,'height':1250},device_scale_factor=1)
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.on('request',lambda request:requests.append(request.url))
        try:
            page.goto(source.as_uri(),timeout=180000)
            page.wait_for_function("document.querySelector('#pp-schedule')?.dataset.ready==='true'",timeout=180000)
            page.evaluate('document.fonts.ready')
            overview=page.locator('#rank-step-time')
            overview.locator('tbody tr').first.wait_for()
            overview.get_by_role('switch',name='百分比显示').uncheck()
            page.mouse.move(0,0)
            overview.screenshot(path=str(out/'overview.png'),animations='disabled')
            shots.append({'file':'overview.png','feature':'全局总览','mode':'时间表，秒'})
            parallel=page.locator('#pp-schedule')
            picker=parallel.locator('[data-pp=stream-picker] > summary')
            picker.click();parallel.locator('input[data-stream=compute]').check();picker.click()
            parallel.scroll_into_view_if_needed()
            page.mouse.move(0,0)
            page.wait_for_timeout(100)
            parallel.screenshot(path=str(out/'parallel.png'),animations='disabled')
            shots.append({'file':'parallel.png','feature':'5D并行通信图','streams':['compute','communication'],
                          'domains':parallel.locator('input[data-domain]:checked').evaluate_all('(items)=>items.map(e=>e.dataset.domain)')})
            if any(url.startswith(('http:','https:')) for url in requests):errors.append('截图过程中存在网络资源请求')
            if errors:raise RuntimeError('截图页面错误：'+str(errors))
            for shot in shots:shot['sha256']=hashlib.sha256((out/shot['file']).read_bytes()).hexdigest()
            metadata={'source_html_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'viewport':{'width':1600,'height':1250},
                      'browser_version':browser.version,'screenshots':shots,'errors':errors}
            (out/'preview_manifest.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        finally:
            browser.close()
    print(json.dumps({'output_dir':str(out),'screenshots':shots},ensure_ascii=False,indent=2))


if __name__=='__main__':
    main()
